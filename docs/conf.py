"""Sphinx configuration for the RobStatTM-Py documentation site.

The site is built from the hand-curated Markdown pages in this folder
(``api/wrappers/*.md`` are generated by ``scripts/render_rd.py``). It does
NOT import ``robstattm_py`` at build time, so the docs build without R/rpy2
installed, handy for CI and Read the Docs.

Build locally::

    cd robstattm-py
    python -m sphinx -b html docs docs/_build/html
"""
from __future__ import annotations

# -- Project information -----------------------------------------------------
project = "RobStatTM-Py"
author = "Aakarsh Gupta"
copyright = "2026, Aakarsh Gupta"
release = "0.0.1.dev0"

# -- General configuration ---------------------------------------------------
extensions = [
    "myst_parser",        # Markdown support
    "sphinx_design",      # grids, cards, tabs
    "sphinx_copybutton",  # copy button on code blocks
]

# MyST extensions we actually use across the pages.
myst_enable_extensions = [
    "colon_fence",    # ::: fenced directives (used on the landing page only)
    "deflist",
    "fieldlist",
    "attrs_inline",
]
