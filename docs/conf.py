# Files/folders Sphinx should not try to build as pages.
exclude_patterns = [
    "_build",
    "_rd_json",
    "examples",
    "scripts",
    "templates",
    "misc",
    # Contributor-facing design docs now live in `dev/design/` (outside the
    # docs tree), so they are no longer listed here. The two maintainer files
    # that remain in `docs/` are kept out of the built site:
    "RELEASING.md",
    "README.md",
]

# -- HTML output -------------------------------------------------------------
html_theme = "furo"
html_title = "RobStatTM-Py"
